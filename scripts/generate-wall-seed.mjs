/**
 * Generate supabase/seed-wall.sql from src/lib/wallSeeds.js.
 *
 * The seeds are authored once, in JS, because the app has to draw a wall with
 * no database at all (§1 is guest-first, and local development usually has no
 * Supabase env set). The SQL is the derived copy, so run this after editing
 * wallSeeds.js and commit both.
 *
 *   node scripts/generate-wall-seed.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

import { WALL_SEEDS } from "../src/lib/wallSeeds.js";
import { MOODSCREEN_PAYLOAD_VERSION } from "../src/lib/moodscreenPayload.js";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../supabase/seed-wall.sql");

/** Single quotes doubled — these are authored strings, not user input. */
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

/**
 * The v3 payload, exactly as a stored Moodscreen keeps it, so a seed reads
 * through normalizeStoredMoodscreen with no special case.
 *
 * The timestamp is carried across exactly as authored — without a zone, and not
 * converted to UTC. That is the one place a seed is deliberately not like a
 * real Moodscreen. A real one records an instant, and §7.4's tint follows it
 * into whatever zone it is read in. A seed records no instant: it is a fixture,
 * chosen so the three night bands are all visible in one row of the wall, and
 * stamping it UTC here would shift every seed by the reader's offset and put
 * the 3am card in the afternoon for half the world.
 */
function payload(seed) {
  const at = seed.at;
  return {
    version: MOODSCREEN_PAYLOAD_VERSION,
    name: seed.name,
    location: seed.location,
    mood: seed.mood,
    surface: seed.surface,
    statement: seed.statement,
    /* Read from the seed, not blanked. Most carry no link and resolve to ""
     * exactly as before; the few that do would otherwise reach the database
     * with the field silently dropped, and the page would look like it could
     * not render a link rather than like there was none to render. */
    link: seed.link || "",
    themeId: seed.themeId,
    avatarUrl: null,
    created_at: at,
    updated_at: at,
  };
}

const rows = WALL_SEEDS.map(
  (s, i) =>
    `  (${q(s.username)}, ${q(s.name)}, ${q(s.location)}, ${q(
      JSON.stringify(payload(s)),
    )}::JSONB, ${i})`,
).join(",\n");

const sql = `-- GENERATED by scripts/generate-wall-seed.mjs — do not edit.
-- Source: src/lib/wallSeeds.js. Regenerate after changing it.
--
-- Run in the Supabase SQL editor after schema.sql. Re-running replaces the
-- seeds in place rather than duplicating them.

INSERT INTO public.wall_seeds (username, name, location, data, sort_order)
  VALUES
${rows}
ON CONFLICT (username)
  DO UPDATE SET
    name = EXCLUDED.name,
    location = EXCLUDED.location,
    data = EXCLUDED.data,
    sort_order = EXCLUDED.sort_order;
`;

writeFileSync(out, sql, "utf8");
console.log(`Wrote ${out} — ${WALL_SEEDS.length} seeds.`);
